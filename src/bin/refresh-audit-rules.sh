set -euo pipefail

IDENTITY_OUT=/etc/audit/rules.d/40-ir-stack-identity.rules
SSH_OUT=/etc/audit/rules.d/42-ir-stack-sshkeys.rules
TMP_ID="$(mktemp)"; TMP_SSH="$(mktemp)"
trap 'rm -f "$TMP_ID" "$TMP_SSH"' EXIT

add_watch() {
    local out="$1" path="$2" perms="$3" key="$4"
    [[ -e "$path" ]] || return 0
    if [[ "$path" =~ [[:space:]] ]]; then
        logger -t ir-stack-audit -- "skip audit watch con whitespace: $path"
        return 0
    fi
    printf -- '-w %s -p %s -k %s\n' "$path" "$perms" "$key" >> "$out"
}

{
    echo '## Generated by IR Stack - identity / privilege watches'
} > "$TMP_ID"
for p in /etc/passwd /etc/shadow /etc/group /etc/gshadow; do add_watch "$TMP_ID" "$p" wa identity; done
add_watch "$TMP_ID" /etc/sudoers wa privilege
add_watch "$TMP_ID" /etc/sudoers.d/ wa privilege
add_watch "$TMP_ID" /etc/ssh/sshd_config wa sshcfg
for spec in \
    '/usr/sbin/useradd:x:user_mgmt' '/usr/sbin/usermod:x:user_mgmt' '/usr/sbin/userdel:x:user_mgmt' \
    '/usr/bin/passwd:x:passwd_mgmt' '/usr/sbin/visudo:x:sudo_change'; do
    IFS=: read -r p perms key <<< "$spec"
    add_watch "$TMP_ID" "$p" "$perms" "$key"
done

{
    echo '## Generated by IR Stack - SSH key files and existing .ssh directories'
} > "$TMP_SSH"
while IFS= read -r -d '' d; do add_watch "$TMP_SSH" "$d/" wa sshkeys; done < <(find /root /home -xdev -type d -name .ssh -print0 2>/dev/null | sort -z || true)
while IFS= read -r -d '' f; do add_watch "$TMP_SSH" "$f" wa sshkeys; done < <(find /root /home -xdev -type f -name authorized_keys -print0 2>/dev/null | sort -z || true)

install -o root -g root -m 600 "$TMP_ID" "$IDENTITY_OUT"
install -o root -g root -m 600 "$TMP_SSH" "$SSH_OUT"

enabled="$(auditctl -s 2>/dev/null | awk '$1=="enabled" {print $2; exit}')"
if [[ "$enabled" == 2 ]]; then
    logger -t ir-stack-audit -- 'auditd immutable: regole salvate su disco, caricamento rinviato al reboot'
    echo 'ATTENZIONE: auditd è immutable (enabled=2). Le nuove regole saranno applicate al reboot.' >&2
    exit 10
fi
if ! augenrules --load; then
    echo 'ERRORE: impossibile caricare le regole audit IR Stack.' >&2
    exit 2
fi
printf 'Regole audit IR Stack rigenerate e caricate.\n'
